const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 80);

const topics = (names: string[]): Topic[] =>
  names.map((n) => ({ slug: slugify(n), name: n.trim() }));

