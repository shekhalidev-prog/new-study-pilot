export const findSubject = (slug: string) =>
  subjects.find((s) => s.slug === slug);

export const findTopic = (subjectSlug: string, unitId: string, topicSlug: string) => {
  const s = findSubject(subjectSlug);
  const u = s?.units.find((u) => u.id === unitId);
  const t = u?.topics.find((t) => t.slug === topicSlug);
  return s && u && t ? { subject: s, unit: u, topic: t } : null;
};
